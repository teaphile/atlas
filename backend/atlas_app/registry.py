"""Source catalog is also the public attribution and credential contract.
A reachable API is not a promise of current observations or universal coverage.
"""

from .schemas import SourceDefinition as S


def source(
    id,
    name,
    provider,
    category,
    scope,
    nature,
    coverage,
    ttl,
    docs,
    attribution,
    license,
    description,
    default=False,
    key=None,
    stale=None,
):
    return S(
        id=id,
        name=name,
        provider=provider,
        category=category,
        scope=scope,
        nature=nature,
        coverage=coverage,
        ttl_seconds=ttl,
        max_stale_seconds=stale or min(ttl * 6, 86400),
        docs_url=docs,
        attribution=attribution,
        license_note=license,
        description=description,
        enabled_by_default=default,
        key_env=key,
    )


