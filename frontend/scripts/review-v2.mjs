import {chromium} from '@playwright/test';
import AxeBuilder from '@axe-core/playwright';
import fs from 'node:fs/promises';
const dir='../docs/v2';await fs.mkdir(dir,{recursive:true});
const browser=await chromium.launch({headless:true,args:['--no-sandbox','--enable-unsafe-swiftshader']});
const context=await browser.newContext({viewport:{width:1440,height:960},deviceScaleFactor:1});
const page=await context.newPage();
const errors=[],http=[];page.on('pageerror',e=>errors.push(String(e)));page.on('response',r=>{if(r.status()>=400)http.push({status:r.status(),url:r.url()});});
await page.goto('http://127.0.0.1:7860',{waitUntil:'domcontentloaded'});
await page.locator('.map-stage[data-map-ready="true"]').waitFor({timeout:40000});
await page.getByText('Reading environmental models…').waitFor({state:'hidden',timeout:45000}).catch(()=>{});
await page.screenshot({path:dir+'/desktop-overview-progress.png'});
await page.getByRole('button',{name:'Intelligence',exact:true}).click();
await page.getByRole('button',{name:'Signal Lab',exact:true}).click();
await page.locator('.derived-metrics').waitFor({timeout:45000});
await page.screenshot({path:dir+'/desktop-lab-progress.png'});
const axe=await new AxeBuilder({page}).withTags(['wcag2a','wcag2aa','wcag21aa']).analyze();
await fs.writeFile(dir+'/a11y-progress.json',JSON.stringify({violations:axe.violations,incomplete:axe.incomplete.map(i=>({id:i.id,nodes:i.nodes.length}))},null,2));
await page.setViewportSize({width:390,height:844});
await page.screenshot({path:dir+'/phone-lab-progress.png'});
await page.getByRole('button',{name:'Overview',exact:true}).click();
await page.locator('.map-stage[data-map-ready="true"]').waitFor({timeout:40000});
await page.screenshot({path:dir+'/phone-overview-progress.png'});
const metrics=await page.evaluate(()=>({width:innerWidth,scroll:document.documentElement.scrollWidth,body:document.body.scrollWidth,main:document.querySelector('.workspace-main')?.getBoundingClientRect().toJSON(),map:document.querySelector('.map-stage')?.getBoundingClientRect().toJSON()}));
await fs.writeFile(dir+'/browser-progress.json',JSON.stringify({errors,http,metrics,violations:axe.violations.map(v=>({id:v.id,impact:v.impact,nodes:v.nodes.length}))},null,2));
console.log(JSON.stringify({errors,http,metrics,violations:axe.violations.map(v=>({id:v.id,impact:v.impact,nodes:v.nodes.length}))},null,2));
await browser.close();
